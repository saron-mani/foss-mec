// Section rule:  +----[ 02 / EVENTS ]------------------------+
export const rule = (label, width = 56) => {
  const mid = "[ " + label + " ]";
  const rest = Math.max(4, width - mid.length - 2);
  return "+--" + mid + "-".repeat(rest) + "+";
};

